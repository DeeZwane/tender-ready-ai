
import { useState } from 'react';

import { CheckCircle2, Info } from 'lucide-react';

export default function Checklist({ analysis }: { analysis: any }) {

  const [checkedItems, setCheckedItems] = useState<number[]>([]);

  const data = typeof analysis === 'string' ? JSON.parse(analysis) : analysis;

  // Use AI data, or fallback to a default list

  const items = data?.required_documents || ['Company Registration', 'Tax Clearance', 'B-BBEE Certificate'];

  const toggleItem = (index: number) => {

    setCheckedItems((current) =>

      current.includes(index) ? current.filter((i) => i !== index) : [...current, index]

    );

  };

  const progress = items.length > 0 ? Math.round((checkedItems.length / items.length) * 100) : 0;

  return (
<div className="panel p-8 max-w-4xl mx-auto mt-10">
<h1 className="text-3xl font-bold text-navy-900 mb-2">Requirements Checklist</h1>
<p className="text-muted mb-8">Ensure you have all required documents.</p>
<div className="w-full h-2 rounded-full bg-canvas overflow-hidden mb-8">
<div className="h-full bg-green-600 transition-all" style={{ width: `${progress}%` }} />
</div>
<div className="space-y-3">

        {items.map((item: string, index: number) => {

          const isChecked = checkedItems.includes(index);

          return (
<label key={index} className={`flex items-start gap-4 p-4 rounded-xl border cursor-pointer ${isChecked ? 'border-green-600 bg-green-50' : 'border-line hover:bg-canvas'}`}>
<input type="checkbox" checked={isChecked} onChange={() => toggleItem(index)} className="mt-1 h-5 w-5 accent-green-600 shrink-0" />
<span className={`flex-1 font-medium ${isChecked ? 'text-green-700 line-through' : 'text-navy-900'}`}>

                {item}
</span>

              {isChecked && <CheckCircle2 className="text-green-700 shrink-0" size={20} />}
</label>

          );

        })}
</div>
<div className="mt-8 rounded-xl bg-blue-50 p-4 flex gap-3 items-start">
<Info className="text-blue-700 shrink-0 mt-0.5" size={20} />
<p className="text-sm text-navy-800">

          This checklist was generated by AI based on the uploaded document. Always verify against the original tender.
</p>
</div>
</div>

  );

}
